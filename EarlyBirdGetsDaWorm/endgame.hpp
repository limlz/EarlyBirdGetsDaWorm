#pragma once

/******************************************************************************************
    @brief  Loads all endgame screen textures, fonts, and UI assets.
******************************************************************************************/
void Endgame_Load();

/******************************************************************************************
    @brief  Resets endgame screen state, fade timers, and result display variables.
******************************************************************************************/
void Endgame_Initialize();

/******************************************************************************************
    @brief  Handles endgame screen input and fade/transition logic each frame.
******************************************************************************************/
void Endgame_Update();

/******************************************************************************************
    @brief  Renders the endgame results screen with statistics and end-reason text.
******************************************************************************************/
void Endgame_Draw();

/******************************************************************************************
    @brief  Releases session-specific endgame data (vectors, timers) between plays.
******************************************************************************************/
void Endgame_Free();

/******************************************************************************************
    @brief  Unloads all endgame textures and font resources from memory.
******************************************************************************************/
void Endgame_Unload();

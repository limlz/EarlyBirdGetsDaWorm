#pragma once

/******************************************************************************************
    @brief  Loads all main menu textures, fonts, and UI assets.
******************************************************************************************/
void MainMenu_Load();

/******************************************************************************************
    @brief  Resets menu state, button scales, and animation timers for a fresh entry.
******************************************************************************************/
void MainMenu_Initialize();

/******************************************************************************************
    @brief  Handles menu input (Play, Options, Credits, Quit) and hover animations.
******************************************************************************************/
void MainMenu_Update();

/******************************************************************************************
    @brief  Renders the main menu background, title animation, and interactive buttons.
******************************************************************************************/
void MainMenu_Draw();

/******************************************************************************************
    @brief  Releases session-specific menu data between state transitions.
******************************************************************************************/
void MainMenu_Free();

/******************************************************************************************
    @brief  Unloads all main menu textures and font resources from memory.
******************************************************************************************/
void MainMenu_Unload();
